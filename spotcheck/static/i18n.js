const LANGUAGES = Object.keys(MESSAGES);

function detectLanguage() {
  try {
    const saved = localStorage.getItem("spotcheck-lang");
    if (LANGUAGES.includes(saved)) return saved;
  } catch {}
  return (navigator.languages || [navigator.language || "en"]).some((l) => /^cs|^sk/i.test(l)) ? "cs" : "en";
}

let currentLanguage = detectLanguage();

function setLanguage(lang) {
  if (!LANGUAGES.includes(lang)) return;
  currentLanguage = lang;
  try { localStorage.setItem("spotcheck-lang", lang); } catch {}
}

const locale = () => (currentLanguage === "cs" ? "cs-CZ" : "en-GB");

const hasMessage = (key) => key in MESSAGES.en;

const PLURAL_CATEGORIES = { en: ["one", "other"], cs: ["one", "few", "other"] };

function pluralForm(lang, value, forms) {
  const index = PLURAL_CATEGORIES[lang].indexOf(new Intl.PluralRules(lang).select(Number(value)));
  return forms[index === -1 ? forms.length - 1 : Math.min(index, forms.length - 1)];
}

function t(key, params = {}) {
  const lang = key in MESSAGES[currentLanguage] ? currentLanguage : "en";
  const text = MESSAGES[lang][key] ?? key;
  return text
    .replace(/\{(\w+)\|([^}]*)\}/g, (match, name, forms) => (name in params ? pluralForm(lang, params[name], forms.split("|")) : match))
    .replace(/\{(\w+)\}/g, (match, name) => (name in params ? String(params[name]) : match));
}

function translatePage(root = document) {
  document.documentElement.lang = currentLanguage;
  root.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll("[data-i18n-title]").forEach((el) => { el.title = t(el.dataset.i18nTitle); });
  root.querySelectorAll("[data-i18n-aria]").forEach((el) => { el.setAttribute("aria-label", t(el.dataset.i18nAria)); });
  root.querySelectorAll("[data-i18n-placeholder]").forEach((el) => { el.placeholder = t(el.dataset.i18nPlaceholder); });
}
